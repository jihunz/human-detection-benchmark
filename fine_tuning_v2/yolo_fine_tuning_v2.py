"""
YOLO fine-tuning with two prepared datasets (non-CLI)
-----------------------------------------------------
This script combines two pre-extracted datasets into a unified YOLO dataset,
performs a grouped train/val split, generates data.yaml and launches training.

Datasets
- AI-Hub fall_end frames: produced by extract_ai_hub_indoor_fall.py
  Structure: ROOT/images/*.jpg, ROOT/labels/*.txt  (class 0=person)
- CAUCAFall last frames: produced by caucafall_extract_last_frame.py
  Structure: ROOT/*.png + ROOT/*.txt (paired); labels may need normalization

Notes
- CAUCAFall labels are normalized to single-class 'person' (id=0) by rewriting
  all label lines to class id 0 during combination (no swapping).
- Files are hard-linked into the combined dataset when possible (saves space);
  otherwise symlink; if both fail, copy.
- Train/val split is grouped to avoid cross-leakage:
  * AI-Hub group id: stem before "_frame" (video-level)
  * CAUCA group id: prefix before "__" in filename (as generated by copier)

Edit the [User Config] block and run.
"""

from __future__ import annotations

import os
import sys
import shutil
from pathlib import Path
import random
from typing import List, Tuple, Optional
import yaml
import torch

from ultralytics import YOLO


# ================== [User Config] ==================
# Sources (produced by previous scripts)
AIHUB_ROOT   = Path("train/_fall_frame_dataset")           # has images/, labels/
CAUCA_ROOT   = Path("train/_caucafall_last_frames")        # flat png+txt pairs

# Combined dataset output (will be created)
COMBINED_ROOT = Path("train/_mix_dataset")                 # images/, labels/, _lists/

# Training config
VAL_RATIO   = 0.2
RANDOM_SEED = 42
CLASS_NAMES = ["person"]

# Weights
CKPT_PATH   = Path("")    # set to a local .pt to use; else empty to use alias
CKPT_ALIAS  = "yolo12n.pt" # ultralytics hub alias (auto-download)

# Device: prefer MPS on macOS, else CUDA if available, else CPU
os.environ.setdefault("PYTORCH_ENABLE_MPS_FALLBACK", "1")

# ===================================================

IMG_EXTS = {".jpg", ".jpeg", ".png", ".bmp", ".webp"}


def safe_link_or_copy(src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    try:
        os.link(src, dst)
        return
    except Exception:
        pass
    try:
        if dst.exists():
            dst.unlink()
        dst.symlink_to(src)
        return
    except Exception:
        pass
    shutil.copy2(src, dst)


def resolve_ckpt() -> str:
    if CKPT_PATH and CKPT_PATH.exists() and CKPT_PATH.is_file():
        print(f"[weights] Using local checkpoint: {CKPT_PATH}")
        return str(CKPT_PATH)
    print(f"[weights] Using alias '{CKPT_ALIAS}' (auto-download)")
    return CKPT_ALIAS


# -------------------------
# Collect from AI-Hub root
# -------------------------
def collect_aih_pairs(root: Path) -> List[Tuple[Path, Path, str]]:
    """Return (img, lbl, group_id) tuples from AI-Hub root (images/, labels/)."""
    imgs_dir = root / "images"
    lbls_dir = root / "labels"
    if not imgs_dir.is_dir() or not lbls_dir.is_dir():
        return []
    out: List[Tuple[Path, Path, str]] = []
    for img in sorted(imgs_dir.glob("*")):
        if img.suffix.lower() not in IMG_EXTS:
            continue
        lbl = lbls_dir / (img.stem + ".txt")
        if not lbl.is_file():
            continue
        # group id: part before _frame
        stem = img.stem
        pre = stem.split("_frame")[0] if "_frame" in stem else stem
        gid = f"aih::{pre}"
        out.append((img, lbl, gid))
    return out


# -------------------------------
# Collect from CAUCA (flat folder)
# -------------------------------
def collect_cauca_pairs(root: Path) -> List[Tuple[Path, Path, str]]:
    """Return (img, lbl, group_id) tuples from a flat folder of png/txt pairs."""
    if not root.is_dir():
        return []
    out: List[Tuple[Path, Path, str]] = []
    for img in sorted(root.glob("*")):
        if img.suffix.lower() not in IMG_EXTS:
            continue
        lbl = img.with_suffix(".txt")
        if not lbl.is_file():
            continue
        # file saved earlier as: {prefix}__{orig_stem}.png
        stem = img.stem
        prefix = stem.split("__")[0] if "__" in stem else stem
        gid = f"cau::{prefix}"
        out.append((img, lbl, gid))
    return out


def rewrite_to_class0(src_lbl: Path, dst_lbl: Path) -> None:
    """Rewrite all YOLO label lines to class id 0."""
    dst_lbl.parent.mkdir(parents=True, exist_ok=True)
    lines_out: List[str] = []
    with src_lbl.open("r", encoding="utf-8") as f:
        for line in f:
            s = line.strip()
            if not s:
                continue
            parts = s.split()
            if not parts:
                continue
            parts[0] = "0"
            lines_out.append(" ".join(parts))
    with dst_lbl.open("w", encoding="utf-8") as f:
        f.write("\n".join(lines_out) + ("\n" if lines_out else ""))


# ------------------------------------
# Build combined images/labels structure
# ------------------------------------
def build_combined_dataset(aih_pairs: List[Tuple[Path, Path, str]],
                           cau_pairs: List[Tuple[Path, Path, str]],
                           out_root: Path) -> List[Tuple[Path, Path, str]]:
    """Link/copy images and write labels into a unified images/labels directory.
    Returns a list of (new_img_path, new_lbl_path, group_id).
    """
    images_dir = out_root / "images"
    labels_dir = out_root / "labels"
    if out_root.exists():
        # Do not wipe entire root; only ensure subdirs exist
        images_dir.mkdir(parents=True, exist_ok=True)
        labels_dir.mkdir(parents=True, exist_ok=True)
    else:
        images_dir.mkdir(parents=True)
        labels_dir.mkdir(parents=True)

    result: List[Tuple[Path, Path, str]] = []

    # AI-Hub: keep labels as-is (already person=0)
    for img, lbl, gid in aih_pairs:
        new_name = f"aih_{img.stem}{img.suffix.lower()}"
        new_img = images_dir / new_name
        new_lbl = labels_dir / (Path(new_name).stem + ".txt")
        safe_link_or_copy(img, new_img)
        shutil.copy2(lbl, new_lbl)
        result.append((new_img, new_lbl, gid))

    # CAUCA: normalize labels to class 0 then write
    for img, lbl, gid in cau_pairs:
        new_name = f"cau_{img.stem}{img.suffix.lower()}"
        new_img = images_dir / new_name
        new_lbl = labels_dir / (Path(new_name).stem + ".txt")
        safe_link_or_copy(img, new_img)
        rewrite_to_class0(lbl, new_lbl)
        result.append((new_img, new_lbl, gid))

    return result


# ------------------
# Split train vs val
# ------------------
def split_by_group(pairs: List[Tuple[Path, Path, str]], val_ratio: float, seed: int):
    random.seed(seed)
    from collections import defaultdict

    groups = defaultdict(list)
    for img, lbl, gid in pairs:
        groups[gid].append((img, lbl))

    group_ids = list(groups.keys())
    random.shuffle(group_ids)
    val_count = max(1, int(len(group_ids) * val_ratio))
    # Ensure at least one group remains for train
    if val_count >= len(group_ids) and len(group_ids) > 1:
        val_count = len(group_ids) - 1
    val_set = set(group_ids[:val_count])

    train_imgs, val_imgs = [], []
    for gid, items in groups.items():
        (val_imgs if gid in val_set else train_imgs).extend([img for img, _ in items])
    return train_imgs, val_imgs


def write_list_file(paths: List[Path], out_file: Path) -> None:
    out_file.parent.mkdir(parents=True, exist_ok=True)
    with out_file.open("w", encoding="utf-8") as f:
        for p in paths:
            f.write(str(p.resolve()) + "\n")


def make_data_yaml(root: Path, train_txt: Path, val_txt: Path, class_names: List[str]) -> Path:
    data = {
        "path": str(root.resolve()),
        "train": str(train_txt.resolve()),
        "val": str(val_txt.resolve()),
        "names": {i: n for i, n in enumerate(class_names)},
    }
    out = root / "data.auto.yaml"
    with out.open("w", encoding="utf-8") as f:
        yaml.safe_dump(data, f, sort_keys=False)
    return out


def main() -> None:
    assert AIHUB_ROOT.exists(), f"AI-Hub root not found: {AIHUB_ROOT}"
    assert CAUCA_ROOT.exists(), f"CAUCA root not found: {CAUCA_ROOT}"

    print("[1/6] Collecting pairs from AI-Hub…")
    aih_pairs = collect_aih_pairs(AIHUB_ROOT)
    print(f"  AI-Hub pairs: {len(aih_pairs)}")

    print("[2/6] Collecting pairs from CAUCAFall…")
    cau_pairs = collect_cauca_pairs(CAUCA_ROOT)
    print(f"  CAUCA pairs: {len(cau_pairs)}")

    assert aih_pairs or cau_pairs, "No pairs found in either dataset."

    print("[3/6] Building combined dataset structure…")
    combined_pairs = build_combined_dataset(aih_pairs, cau_pairs, COMBINED_ROOT)
    print(f"  Combined usable pairs: {len(combined_pairs)}")
    assert combined_pairs, "No usable pairs after normalization."

    print("[4/6] Grouped train/val split…")
    train_imgs, val_imgs = split_by_group(combined_pairs, VAL_RATIO, RANDOM_SEED)
    print(f"  train: {len(train_imgs)} | val: {len(val_imgs)}")
    assert train_imgs and val_imgs, "Empty train/val split. Adjust VAL_RATIO or data."

    print("[5/6] Writing lists and data.yaml…")
    lists_dir = COMBINED_ROOT / "_lists"
    train_txt = lists_dir / "train.txt"
    val_txt = lists_dir / "val.txt"
    write_list_file(train_imgs, train_txt)
    write_list_file(val_imgs, val_txt)
    data_yaml = make_data_yaml(COMBINED_ROOT, train_txt, val_txt, CLASS_NAMES)
    print(f"  data.yaml: {data_yaml}")

    print(f"[6/6] Launching training | device=mps")
    ckpt_to_use = resolve_ckpt()
    try:
        model = YOLO(ckpt_to_use)
    except Exception as e:
        print("[ERROR] Failed to load weights:", e)
        print("        pip install -U ultralytics and retry.")
        sys.exit(1)

    model.train(
        data=str(data_yaml),
        epochs=100,
        patience=20,
        imgsz=640,
        batch=8,
        device="mps",
        workers=2,
        optimizer="SGD",
        lr0=0.01,
        momentum=0.937,
        weight_decay=5e-4,
        amp=False,      # recommended for MPS
        cos_lr=True,
        cache=False,
        verbose=True,
    )

    # quick val
    metrics = model.val(
        data=str(data_yaml),
        imgsz=640,
        device="mps",
        workers=2,
        verbose=False,
    )
    print("Validation:", metrics)


if __name__ == "__main__":
    main()
